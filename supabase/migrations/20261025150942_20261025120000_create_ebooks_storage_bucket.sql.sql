/*
# Create private 'ebooks' storage bucket for ebook HTML files

## Plain-English Summary
Creates a private storage bucket called `ebooks` to hold the ebook HTML
files (the print-ready playbooks like "Calm in the Storm"). The bucket is
private so ebook files cannot be accessed by guessing a URL. Reads are
served via short-lived signed URLs generated by the app, which protects
paid content. Uploads and deletes are restricted to the admin account
(matching the existing admin@carelearn.uk pattern used for the podcasts
bucket).

## Storage bucket
- `ebooks` (private)

## Security (storage.objects RLS policies)
- SELECT: anon + authenticated can read objects in the `ebooks` bucket.
  This is required so the Supabase client can create signed URLs for
  visitors to open ebooks in a new browser tab for reading.
- INSERT: restricted to the admin account (admin@carelearn.uk) so only
  the site owner can upload ebook files.
- DELETE: restricted to the same admin account so only the site owner
  can remove or replace ebook files.
- UPDATE: restricted to the same admin account.

## Important notes
1. The bucket is created via insert into storage.buckets with public = false.
2. Signed URLs are generated client-side with createSignedUrl; they expire
   after a short window, so permanent sharing of paid content is prevented.
3. The admin gating predicate mirrors the existing podcasts bucket policies.
*/

INSERT INTO storage.buckets (id, name, public)
VALUES ('ebooks', 'ebooks', false)
ON CONFLICT (id) DO NOTHING;

-- SELECT: anon + authenticated can read ebook objects (enables signed URLs)
DROP POLICY IF EXISTS "Ebook files public read access" ON storage.objects;
CREATE POLICY "Ebook files public read access"
  ON storage.objects FOR SELECT
  TO anon, authenticated
  USING (bucket_id = 'ebooks');

-- INSERT: admin only
DROP POLICY IF EXISTS "Ebook files admin upload access" ON storage.objects;
CREATE POLICY "Ebook files admin upload access"
  ON storage.objects FOR INSERT
  TO authenticated
  WITH CHECK (
    bucket_id = 'ebooks'
    AND EXISTS (
      SELECT 1 FROM auth.users
      WHERE users.email = 'admin@carelearn.uk'
      AND users.id = auth.uid()
    )
  );

-- UPDATE: admin only
DROP POLICY IF EXISTS "Ebook files admin update access" ON storage.objects;
CREATE POLICY "Ebook files admin update access"
  ON storage.objects FOR UPDATE
  TO authenticated
  USING (
    bucket_id = 'ebooks'
    AND EXISTS (
      SELECT 1 FROM auth.users
      WHERE users.email = 'admin@carelearn.uk'
      AND users.id = auth.uid()
    )
  )
  WITH CHECK (
    bucket_id = 'ebooks'
    AND EXISTS (
      SELECT 1 FROM auth.users
      WHERE users.email = 'admin@carelearn.uk'
      AND users.id = auth.uid()
    )
  );

-- DELETE: admin only
DROP POLICY IF EXISTS "Ebook files admin delete access" ON storage.objects;
CREATE POLICY "Ebook files admin delete access"
  ON storage.objects FOR DELETE
  TO authenticated
  USING (
    bucket_id = 'ebooks'
    AND EXISTS (
      SELECT 1 FROM auth.users
      WHERE users.email = 'admin@carelearn.uk'
      AND users.id = auth.uid()
    )
  );
